WHERE (r.name = 'TEAM_LEAD' AND p.code IN ('PROJECT_UPDATE', 'MILESTONE_STATUS_UPDATE'))
   OR (r.name IN ('ADMIN', 'PROJECT_MANAGER') AND p.code = 'PROJECT_DELETE')
   OR (r.name = 'ADMIN' AND p.code = 'MILESTONE_STATUS_UPDATE')
ON CONFLICT (role_id, permission_id) DO NOTHING;








